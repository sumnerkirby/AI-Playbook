/* The full tool check: rules. Worst outcome wins; nothing is added up.
   Design: exploratory/feature_concepts/02_tool_check.md, and the gaps in
   exploratory/walkthroughs/solo_financial_adviser.md.

   Each rule:
     outcome   stop (a red line) or condition (a to-do; amber until done)
     when      condition over the answers and the profile (_industry, _team,
               _path, _mode) plus _records (it records or transcribes people)
     reason    why this answer matters
     fix       stop: what would change it. condition: the to-do.
     owner     you | it | supplier | advisor  (it becomes "your IT provider"
               when the profile says so)
     allowed   data classes still allowed meanwhile; the result allows only
               what every rule allows. "Don't know" works this way, so
               uncertainty gives limited use, never green.
     allowed_note   what's still allowed when it isn't about data classes
     standing  for a condition: the rule that stays once the to-do is done
     answer    for a "don't know": the question to answer again. It can't be
               ticked done; it closes only when the answer changes.
     cleanup   a clean-up to-do for something already in use
     where_to_look  show directions: true for data settings, 'mfa' for sign-in
     flag      get_advice, with flag_text
   Legal points are flags to check with an advisor, never conclusions.
   Not yet verified for publication. */

